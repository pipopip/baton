"""Explicit, account-scoped installation of the portable LANE skills and Codex queue bridge.

No live state is copied. This helper never installs the Claude runtime mod, changes
permissions or hook trust, or starts/restarts an agent.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import subprocess
import tomllib

from . import config

MARKER = "<!-- generated by baton lane-workflow; managed skill -->"
SKILLS = ("lane-workflow", "lane-math")


def _homes() -> list[tuple[str, Path]]:
    seen = set()
    homes = []
    for vendor in config.VENDORS:
        for account in config.account_names(vendor):
            home = config.account_dir(vendor, account)
            key = (vendor, config.norm(home.resolve()))
            if key not in seen and home.is_dir():
                seen.add(key)
                homes.append((vendor, home))
    return homes


def _native_codex() -> str:
    exe = config.exe("codex")
    path = Path(exe)
    if os.name == "nt" and (path.suffix.lower() != ".exe" or not path.is_file()):
        raise ValueError("LANE transport requires the native Codex .exe; configure BATON_CODEX_EXE")
    return exe


APPROVAL_KEY, APPROVAL_VALUE = "default_tools_approval_mode", "approve"


def _wanted_mcp(install_home: Path, exe: str) -> dict:
    """The compute-queue server as it must stand in a Codex home. Its tools are pre-approved (owner decision
    2026-11-11): with `approval_policy = "never"` Codex refuses every MCP tool that would need approval, so
    without this a Codex session cannot submit or cancel a job at all. Claude sessions call the same tools
    without a prompt."""
    return {"command": str(config.PYTHON),
            "args": ["-X", "utf8", str(install_home / "mods/compute-queue/bin/codex_bridge.py")],
            "env": {"BATON_CODEX_EXE": exe}, APPROVAL_KEY: APPROVAL_VALUE}


def _with_approval(text: str) -> str:
    """config.toml text with the approval line directly under the [mcp_servers.compute-queue] header (`codex mcp
    add` cannot write it). Unchanged when the table is absent or already carries the key."""
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if line.strip() == "[mcp_servers.compute-queue]":
            end = next((i for i in range(index + 1, len(lines)) if lines[i].lstrip().startswith("[")), len(lines))
            if any(l.split("=")[0].strip() == APPROVAL_KEY for l in lines[index + 1:end]):
                return text
            newline = "\r\n" if line.endswith("\r\n") else "\n"
            if not line.endswith(("\n", "\r")):
                lines[index] = line + newline
            lines.insert(index + 1, f'{APPROVAL_KEY} = "{APPROVAL_VALUE}"{newline}')
            return "".join(lines)
    return text


def _unrelated_config(data: dict) -> dict:
    servers = {}
    for name, value in data.get("mcp_servers", {}).items():
        if name == "compute-queue":
            continue
        server = dict(value)
        # Native Codex omits default empty stdio args when rewriting MCP tables.
        # This is the sole tolerated serialization difference; real arguments stay exact.
        if server.get("command") and server.get("args") == []:
            server.pop("args")
        servers[name] = server
    return {**data, "mcp_servers": servers}


def _mcp_action(home: Path, install_home: Path, exe: str, stamp: str, dry_run: bool) -> str:
    from .install import _backup
    path = home / "config.toml"
    data = tomllib.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    current = data.get("mcp_servers", {}).get("compute-queue")
    wanted = _wanted_mcp(install_home, exe)
    if current == wanted:
        return f"unchanged compute-queue MCP in {path}"
    if current is not None:
        # Ownership requires the exact installed entry point, not merely a familiar server name.
        args = current.get("args") if isinstance(current, dict) else None
        if not isinstance(args, list) or len(args) != 3 or args[:2] != ["-X", "utf8"] or config.norm(args[2]) != config.norm(wanted["args"][2]):
            raise ValueError(f"custom compute-queue MCP collision in {path}; left untouched")
        if any(key not in wanted for key in current) or set(current.get("env", {})) - {"BATON_CODEX_EXE"}:
            raise ValueError(f"custom compute-queue MCP options in {path}; left untouched")
        # The key is in `wanted`, so the check above lets another value through, and `codex mcp add` rewrites the
        # table without the key: _with_approval would then replace the owner's value with "approve".
        if isinstance(current, dict) and APPROVAL_KEY in current and current[APPROVAL_KEY] != APPROVAL_VALUE:
            raise ValueError(f"custom compute-queue MCP options in {path}; left untouched")
    if dry_run:
        return f"would configure compute-queue MCP in {path}"
    _backup(path, stamp)
    original = path.read_bytes() if path.exists() else None
    argv = [exe, "mcp", "add", "compute-queue", "--env", f"BATON_CODEX_EXE={exe}", "--",
            wanted["command"], *wanted["args"]]
    env = config.clean_env()
    env["CODEX_HOME"] = str(home)
    try:
        cp = subprocess.run(argv, env=env, stdin=subprocess.DEVNULL, capture_output=True,
                            text=True, timeout=30, creationflags=config.CREATE_NO_WINDOW)
        if cp.returncode:
            raise ValueError(f"codex mcp add failed for {home} (exit {cp.returncode})")
        written = path.read_bytes()
        approved = _with_approval(written.decode("utf-8")).encode("utf-8")
        if approved != written:
            path.write_bytes(approved)
        actual = tomllib.loads(path.read_text(encoding="utf-8"))
        if actual.get("mcp_servers", {}).get("compute-queue") != wanted:
            raise ValueError(f"codex mcp add did not install the expected bridge in {path}")
        # Native CLI must leave all unrelated configuration semantically intact.
        if _unrelated_config(data) != _unrelated_config(actual):
            raise ValueError(f"codex mcp add changed unrelated configuration in {path}")
    except (OSError, ValueError, subprocess.SubprocessError):
        if original is None:
            path.unlink(missing_ok=True)
        else:
            path.write_bytes(original)
        raise
    return f"configured compute-queue MCP in {path}"


def _compute_hook(home: Path, install_home: Path, stamp: str, dry_run: bool) -> str:
    from .install import _backup, _write_json
    path = home / "hooks.json"
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    script = (install_home / "compute_guard.py").as_posix()
    # Codex executes Windows hooks through PowerShell. A quoted executable is
    # an expression there, so its following -S argument is a parser error.
    # Match the other Baton hooks; install.run rejects paths containing spaces.
    command = f'{Path(config.PYTHON).as_posix()} -S {script}'
    wanted = {"matcher": ".*", "hooks": [{"type": "command", "command": command, "timeout": 10}]}
    hooks = dict(data.get("hooks", {}))
    groups = []
    for group in hooks.get("PreToolUse", []):
        kept = [h for h in group.get("hooks", [])
                if not re.search(r'(?:^|[\s\"])' + re.escape(script) + r'(?:[\s\"]|$)',
                                 str(h.get("command", "")).replace("\\", "/"))]
        if kept:
            groups.append(dict(group, hooks=kept))
    hooks["PreToolUse"] = groups + [wanted]
    if hooks == data.get("hooks"):
        return f"unchanged compute guard in {path}"
    if dry_run:
        return f"would add compute guard in {path}"
    _backup(path, stamp)
    _write_json(path, dict(data, hooks=hooks))
    return f"added compute guard in {path}; review new hooks with Codex /hooks"


def install(stamp: str, dry_run: bool, install_home: Path | None = None) -> list[str]:
    from .install import _backup
    install_home = install_home or config.INSTALL_HOME
    source = config.BATON_HOME / "mods/lane-workflow/skills"
    homes = _homes()
    # Validate all collisions before modifying any target. Resolve directory junctions in place.
    targets = {}
    for _, home in homes:
        for name in SKILLS:
            target = (home / "skills" / name / "SKILL.md").resolve()
            content = (source / name / "SKILL.md").read_text(encoding="utf-8")
            if MARKER not in content:
                raise ValueError(f"unmarked source skill {name}")
            if target.exists() and MARKER not in target.read_text(encoding="utf-8"):
                raise ValueError(f"unmarked skill collision at {target}; left untouched")
            targets[config.norm(target)] = (target, content)
    exe = _native_codex() if any(v == "codex" for v, _ in homes) else ""
    for vendor, home in homes:
        if vendor == "codex":
            _mcp_action(home, install_home, exe, stamp, True)  # preflight custom server collisions
            _compute_hook(home, install_home, stamp, True)
    actions = []
    for target, content in targets.values():
        if target.exists() and target.read_text(encoding="utf-8") == content:
            actions.append(f"unchanged {target}")
            continue
        actions.append(f"{'would install' if dry_run else 'installed'} {target}")
        if not dry_run:
            _backup(target, stamp)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    for vendor, home in homes:
        if vendor == "codex":
            actions.append(_mcp_action(home, install_home, exe, stamp, dry_run))
            actions.append(_compute_hook(home, install_home, stamp, dry_run))
    return actions
