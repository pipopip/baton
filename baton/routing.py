"""Role routing: render per-vendor agent files from routing.toml.

A vendor entry names one ``model`` or a ``models`` chain (preference order).
``resolve`` picks the first model an account can use (Codex: that home's
``models_cache.json``); ``render_claude`` and ``render_codex`` produce the
shared static agent files, ``apply`` writes them (only over files Baton
generated), ``lead_hint`` gives the lead its role table and ``check`` reports
per account which roles are unavailable or degraded.

Codex agent files are rendered per account home (``<home>/agents``, each from that home's
models_cache.json), so an account with a stronger login gets the stronger model; the helpers that
need one model for several accounts (``shared_codex``) remain for an explicit single directory.

Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from baton import config

MARKER = "generated by baton"
CLAUDE_MARK_LINE = "<!-- generated by baton from routing.toml; edit there and run `bt routing apply` -->"
CODEX_MARK_LINE = "# generated by baton from routing.toml; edit there and run bt routing apply"
LEAD_HINT_LIMIT = 1300
LEAD_HINT_PREFIX = {
    "claude": "Subagent roles (Agent tool, subagent_type):",
    "codex": "Agent roles (spawn_agent agent_type):",
}
EFFORTS = ("low", "medium", "high", "xhigh", "max")
CACHE_NAME = "models_cache.json"
ROLE_NAME = re.compile(r"[a-z0-9][a-z0-9-]*")
CLAUDE_MODEL = re.compile(r"claude-(opus|sonnet|haiku|fable)-.*")
CLAUDE_ID = re.compile(r"claude-([a-z]+)((?:-\d{1,2})+)(?:-\d{8})?")
GPT_ID = re.compile(r"gpt-(\d+(?:\.\d+)*)-([a-z]+)")
# Plain YAML scalars are unsafe when they contain ": ", " #", a leading indicator, or quotes/backslashes.
YAML_NEEDS_QUOTES = re.compile(r": |\s#|:$|^[\s\-?:,\[\]{}#&*!|>'\"%@`]|[\"\\\x00-\x1f]")


def short_model(model: str) -> str:
    """Human label for a model id, e.g. claude-haiku-5-5 -> 'Haiku 5.5', gpt-6.1-sol -> 'GPT-6.1 Sol'."""
    claude = CLAUDE_ID.fullmatch(model)
    if claude:
        return f"{claude.group(1).title()} {claude.group(2)[1:].replace('-', '.')}"
    gpt = GPT_ID.fullmatch(model)
    if gpt:
        return f"GPT-{gpt.group(1)} {gpt.group(2).title()}"
    return model


def roles() -> dict[str, dict]:
    return dict(config.routing_config().get("roles", {}))


def _lead() -> dict:
    return dict(config.routing_config().get("lead", {}))


def entry_models(entry) -> list[str]:
    """The model chain of a vendor entry: ``models`` (preference order) or the single ``model``."""
    if not isinstance(entry, dict):
        return []
    chain = entry.get("models")
    if isinstance(chain, list):
        return [m for m in chain if isinstance(m, str) and m]
    return [entry["model"]] if isinstance(entry.get("model"), str) and entry["model"] else []


def supports_vendor(role: dict, vendor: str) -> bool:
    """Only an explicit vendors list excludes a vendor; missing entries remain errors."""
    vendors = role.get("vendors")
    if vendors is None:
        return True
    if not isinstance(vendors, list) or not vendors or any(v not in config.VENDORS for v in vendors):
        raise ValueError("vendors must be a non-empty list of known vendors")
    return vendor in vendors


def _entry(role: dict, vendor: str) -> dict:
    if not supports_vendor(role, vendor):
        raise ValueError(f"role intentionally excludes {vendor}")
    entry = role.get(vendor)
    if not isinstance(entry, dict) or not entry_models(entry) or not entry.get("effort"):
        raise ValueError(f"no {vendor} model and effort configured")
    if isinstance(entry.get("models"), list) and len(entry_models(entry)) != len(entry["models"]):
        raise ValueError(f"{vendor} models must be a list of non-empty strings")
    required = role.get("required_model")
    if required and entry_models(entry) != [required]:
        raise ValueError(f"role requires exactly {required}; fallback models are forbidden")
    return entry


def required_settings(role: dict, vendor: str, account: str) -> tuple[str, str]:
    """Keep an exact model even with unknown availability; reject known incompatibility."""
    entry = _entry(role, vendor)
    required = role.get("required_model")
    if not isinstance(required, str) or not required:
        raise ValueError("required_model must be a non-empty model id")
    path = config.account_dir(vendor, account) / CACHE_NAME
    catalog = _catalog(vendor, account)
    stamp = config.mtime(path)
    auth_stamp = config.mtime(path.parent / "auth.json")
    effort = str(entry["effort"])
    if catalog is None or stamp is None or (auth_stamp and auth_stamp > stamp):
        return required, effort  # native CLI adjudicates; never inherit a different session model
    if required not in catalog or effort not in catalog[required]:
        raise ValueError(f"{vendor}:{account}: required model {required} with effort {effort} is unavailable; no fallback")
    return required, effort


# ----------------------------------------------------------------- availability and resolution

def _read_catalog(path: Path) -> dict[str, list[str]] | None:
    """{slug: supported efforts} from a Codex models_cache.json; None when missing or unreadable."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    models = data.get("models") if isinstance(data, dict) else None
    if not isinstance(models, list):
        return None
    out: dict[str, list[str]] = {}
    for item in models:
        if isinstance(item, dict) and isinstance(item.get("slug"), str):
            levels = item.get("supported_reasoning_levels")
            out[item["slug"]] = [
                lvl["effort"] for lvl in (levels if isinstance(levels, list) else [])
                if isinstance(lvl, dict) and isinstance(lvl.get("effort"), str)
            ]
    return out


def _catalog(vendor: str, account: str) -> dict[str, list[str]] | None:
    """What an account may use, per model (None = unknown). Only Codex homes publish this."""
    if vendor != "codex":
        return None
    return _read_catalog(config.account_dir(vendor, account) / CACHE_NAME)


def available_models(vendor: str, account: str) -> set[str] | None:
    """Model slugs the account's login may use; None when unknown (Claude, missing or unreadable cache)."""
    catalog = _catalog(vendor, account)
    return None if catalog is None else set(catalog)


@dataclass
class Resolved:
    model: str
    effort: str
    degraded: bool = False   # the chosen model is not the chain's first entry
    reason: str = ""         # why, when degraded or the effort was adjusted


def fit_effort(effort: str, levels: list[str]) -> str:
    """``effort`` if supported, else the highest supported level at or below it (lowest above if none)."""
    known = [lvl for lvl in EFFORTS if lvl in levels]
    if not levels or effort in levels or effort not in EFFORTS or not known:
        return effort
    below = [lvl for lvl in known if EFFORTS.index(lvl) < EFFORTS.index(effort)]
    return below[-1] if below else known[0]


def resolve(vendor: str, block: dict, account: str) -> Resolved:
    """Model and effort for ``account`` from a role or lead block (``block[vendor]``) or a vendor entry.

    The first chain model the account can use wins; unknown availability takes the first. When none
    is available the last entry is returned, degraded.
    """
    if block.get("required_model"):
        model, effort = required_settings(block, vendor, account)
        return Resolved(model, effort)
    entry = block[vendor] if isinstance(block.get(vendor), dict) else block
    chain = entry_models(entry)
    if not chain:
        raise ValueError(f"no {vendor} model configured")
    effort = str(entry.get("effort") or "")
    return _resolve_in(vendor, account, chain, effort, _catalog(vendor, account))


def _resolve_in(vendor: str, account: str, chain: list[str], effort: str,
                catalog: dict[str, list[str]] | None) -> Resolved:
    who = f"{vendor}:{account}"
    reasons: list[str] = []
    if catalog is None:
        model = chain[0]
    else:
        usable = [m for m in chain if m in catalog]
        if usable:
            model = usable[0]
            skipped = chain[: chain.index(model)]
            if skipped:
                reasons.append(f"{who} lacks {', '.join(skipped)}; using {model}")
        else:
            model = chain[-1]
            reasons.append(f"{who} has none of {', '.join(chain)}; trying {model}")
    degraded = catalog is not None and (model != chain[0] or model not in catalog)
    levels = catalog.get(model, []) if catalog else []
    fitted = fit_effort(effort, levels) if effort else effort
    if fitted != effort:
        reasons.append(f"{model} does not support effort {effort} (supports {', '.join(levels)}); using {fitted}")
    return Resolved(model, fitted, degraded, "; ".join(reasons))


def fit_for(vendor: str, account: str, model: str, effort: str) -> tuple[str, str]:
    """(effort, why) for ``effort`` on ``model`` as ``account`` can run it: fitted to the model's supported
    levels (Codex catalog), unchanged when they are unknown. ``why`` is empty when nothing was adjusted."""
    levels = (_catalog(vendor, account) or {}).get(model, [])
    fitted = fit_effort(effort, levels) if effort and levels else effort
    if fitted != effort:
        return fitted, f"{model} does not support effort {effort} (supports {', '.join(levels)}); using {fitted}"
    return effort, ""


def account_codex(entry: dict, account: str) -> tuple[str | None, str, str]:
    """(model, effort, why-omitted) for a Codex agent file of one account's home.

    The model is the first chain entry the account's models_cache.json lists (the first entry when the cache
    is unknown); None, with the reason, when it lists none, so the role inherits the session's model.
    """
    chain = entry_models(entry)
    effort = str(entry.get("effort") or "")
    catalog = _catalog("codex", account)
    if catalog is None:
        return chain[0], effort, ""
    for model in chain:
        if model in catalog:
            return model, (fit_effort(effort, catalog[model]) if effort else effort), ""
    return None, effort, f"codex:{account} can use none of [{', '.join(chain)}]"


def _codex_catalogs() -> list[tuple[str, dict[str, list[str]]]]:
    found = []
    for account in config.account_names("codex"):
        catalog = _catalog("codex", account)
        if catalog is not None:
            found.append((account, catalog))
    return found


def shared_codex(entry: dict) -> tuple[str | None, str, str]:
    """(model, effort, why-omitted) for a static Codex agent file shared by every account.

    The model is the first chain entry every Codex account with a models_cache.json can use; None
    (with the reason) when no chain entry is common, so the role inherits the session's model.
    """
    chain = entry_models(entry)
    effort = str(entry.get("effort") or "")
    caches = _codex_catalogs()
    if not caches:
        return chain[0], effort, ""
    for model in chain:
        if all(model in catalog for _, catalog in caches):
            levels = [lvl for lvl in EFFORTS if all(lvl in catalog[model] for _, catalog in caches)]
            return model, (fit_effort(effort, levels) if effort else effort), ""
    accounts = ", ".join(f"codex:{a}" for a, _ in caches)
    return None, effort, f"no model of [{', '.join(chain)}] is available on every Codex account ({accounts})"


def _summary(role: dict) -> str:
    return " ".join(str(role.get("summary", "")).split())


def _description(role: dict, model: str | None, effort: str) -> str:
    return f"{_summary(role).rstrip('.')}. Model {model or 'inherited from the session'}, effort {effort}."


def _instructions(role: dict) -> str:
    return str(role.get("instructions", "")).strip()


def _yaml_scalar(value: str) -> str:
    return json.dumps(value, ensure_ascii=False) if YAML_NEEDS_QUOTES.search(value) else value


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _ml_escape(text: str) -> str:
    """Escape text for a TOML multi-line basic string."""
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def render_claude(name: str, role: dict) -> str:
    entry = _entry(role, "claude")
    model = entry_models(entry)[0]
    lines = [
        "---",
        f"name: bt-{name}",
        f"description: {_yaml_scalar(_description(role, model, entry['effort']))}",
        f"model: {_yaml_scalar(model)}",
        f"effort: {_yaml_scalar(entry['effort'])}",
    ]
    if role.get("readonly"):
        lines.append("disallowedTools: Edit, Write, NotebookEdit")
    if role.get("isolation"):
        lines.append(f"isolation: {_yaml_scalar(str(role['isolation']))}")
    lines += ["---", CLAUDE_MARK_LINE, _instructions(role)]
    return "\n".join(lines) + "\n"


def render_codex(name: str, role: dict, account: str | None = None) -> str:
    """Codex agent file; ``account`` renders it for that account's models, ``None`` for the models every account has."""
    entry = _entry(role, "codex")
    if role.get("required_model"):
        targets = [account] if account is not None else config.account_names("codex")
        for target in targets:
            model, effort = required_settings(role, "codex", target)
        if not targets:
            raise ValueError("required model cannot be verified without a Codex account")
        omitted = ""
    else:
        model, effort, omitted = shared_codex(entry) if account is None else account_codex(entry, account)
    lines = [
        CODEX_MARK_LINE,
        f"name = {_toml_string(f'bt-{name}')}",
        f"description = {_toml_string(_description(role, model, effort))}",
        'developer_instructions = """',
        _ml_escape(_instructions(role)) + "\n" + '"""',
    ]
    if model:
        lines.append(f"model = {_toml_string(model)}")
    else:
        lines.append(f"# model omitted: {omitted}; the role inherits the session's model")
    lines.append(f"model_reasoning_effort = {_toml_string(effort)}")
    if role.get("readonly"):
        lines.append('sandbox_mode = "read-only"')
    return "\n".join(lines) + "\n"


def _default_claude_dir() -> Path:
    return Path.home() / ".claude" / "agents"


def _default_codex_homes() -> dict[str, Path]:
    return {account: config.account_dir("codex", account) for account in config.account_names("codex")}


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def _is_link(path: Path) -> bool:
    """A symlink or a Windows junction (lstat only; a missing path is not a link)."""
    try:
        isjunction = getattr(os.path, "isjunction", None)
        return path.is_symlink() or (isjunction is not None and isjunction(path))
    except OSError:
        return False


def _unlink_dir_link(path: Path) -> None:
    """Remove a directory symlink or junction itself, never its target (no recursive delete)."""
    isjunction = getattr(os.path, "isjunction", None)
    if isjunction is not None and isjunction(path):
        os.rmdir(path)
        return
    try:
        os.unlink(path)
    except OSError:
        os.rmdir(path)


def _migrate_link(directory: Path, dry_run: bool) -> list[str]:
    """Replace ``directory`` (a symlink or junction to another home's agents) with a real directory.

    Only the link is removed; the target and its files stay. Agent files the baton did not generate are
    copied into the new directory first so the account keeps its own hand-written agents.
    """
    if not _is_link(directory):
        return []
    try:
        target = Path(os.path.realpath(directory))
    except OSError:
        target = directory
    actions = [f"replace link {directory} -> {target} with a real directory"]
    if dry_run:
        return actions
    kept: list[Path] = []
    try:
        kept = [f for f in sorted(target.iterdir()) if f.is_file() and not _generated(f)]
    except OSError:
        pass
    _unlink_dir_link(directory)
    directory.mkdir(parents=True, exist_ok=True)
    for f in kept:
        shutil.copy2(f, directory / f.name)
        actions.append(f"copy {f.name} into {directory}")
    return actions


def _generated(path: Path) -> bool:
    try:
        return MARKER in _read(path)
    except OSError:
        return False


def apply(claude_dir=None, codex_dir=None, dry_run: bool = False, codex_homes=None) -> list[str]:
    """Write bt-<role>.md and bt-<role>.toml; return one action line per file touched or skipped.

    Claude files go to ``claude_dir`` (default ``~/.claude/agents``). Codex files go to ``<home>/agents`` of
    every Codex account (``codex_homes``: {account: home}, default the configured accounts), each rendered
    for that account's models; a home whose ``agents`` is a symlink or junction (the old shared layout) is
    first turned into a real directory. ``codex_dir`` writes one directory rendered for the models every
    account has instead.

    A file is overwritten only when it is absent or carries the generated marker. Marked
    bt-*.md / bt-*.toml files whose role is no longer configured are deleted. Unmarked files
    are never read for deletion or written.
    """
    targets: list[tuple[str, Path, str, str | None]] = [
        ("claude", Path(claude_dir) if claude_dir else _default_claude_dir(), ".md", None)]
    if codex_dir:
        targets.append(("codex", Path(codex_dir), ".toml", None))
    else:
        for account, home in (codex_homes if codex_homes is not None else _default_codex_homes()).items():
            targets.append(("codex", Path(home) / "agents", ".toml", account))
    current = roles()
    actions: list[str] = []
    for vendor, directory, suffix, account in targets:
        if account is not None and not Path(directory).parent.is_dir():
            actions.append(f"skip {directory}: codex:{account} has no home directory yet")
            continue
        if vendor == "codex" and account is not None:
            migrated = _migrate_link(directory, dry_run)
            actions.extend(migrated)
            if migrated and dry_run:      # it would start empty: do not report the old target's files as ours
                for name, role in current.items():
                    if not supports_vendor(role, vendor):
                        continue
                    try:
                        render_codex(name, role, account)
                        actions.append(f"create {directory / f'bt-{name}{suffix}'}")
                    except ValueError as exc:
                        actions.append(f"skip {directory / f'bt-{name}{suffix}'}: {exc}")
                continue
        for name, role in current.items():
            path = directory / f"bt-{name}{suffix}"
            if not supports_vendor(role, vendor):
                if path.exists() and _generated(path):
                    actions.append(f"delete excluded {path}")
                    if not dry_run:
                        path.unlink()
                continue
            try:
                content = render_claude(name, role) if vendor == "claude" else render_codex(name, role, account)
            except ValueError as exc:
                if role.get("required_model") and path.exists() and _generated(path):
                    actions.append(f"delete unavailable {path}")
                    if not dry_run:
                        path.unlink()
                actions.append(f"skip {path}: {exc}")
                continue
            if path.exists():
                if MARKER not in _read(path):
                    actions.append(f"skip (not generated by baton) {path}")
                    continue
                if _read(path) == content:
                    actions.append(f"unchanged {path}")
                    continue
                verb = "update"
            else:
                verb = "create"
            actions.append(f"{verb} {path}")
            if not dry_run:
                directory.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob(f"bt-*{suffix}")):
            if not path.is_file() or path.name[len("bt-"):-len(suffix)] in current:
                continue
            if MARKER not in _read(path):
                continue
            actions.append(f"delete {path}")
            if not dry_run:
                path.unlink()
    return actions


def _shorten(text: str, width: int) -> str:
    if len(text) <= width:
        return text
    if width <= 3:
        return text[:width]
    head = text[: width - 3]
    cut = head.rsplit(" ", 1)[0] if " " in head else head
    return cut.rstrip(" ,;:") + "..."


def _compose(prefix: str, heads: list[str], summaries: list[str], limit: int) -> str:
    def build(texts: list[str]) -> str:
        return "\n".join([prefix] + [head + text for head, text in zip(heads, texts)])

    text = build(summaries)
    if len(text) <= limit or not heads:
        return text
    fixed = len(build([""] * len(heads)))
    budget = max(0, (limit - fixed) // len(heads))
    return build([_shorten(s, budget) for s in summaries])


def _hint_model(vendor: str, entry: dict, account: str | None = None) -> str:
    """Short label of the model the agent file of ``account`` (Codex; default main) will use ('best available' when it inherits)."""
    if vendor == "codex":
        model = account_codex(entry, account or "main")[0]
        return short_model(model) if model else "best available"
    return short_model(entry_models(entry)[0])


def lead_hint(vendor: str, account: str | None = None) -> str:
    """Role table for the lead's session start, at most LEAD_HINT_LIMIT characters (Codex: for ``account``, default main)."""
    if vendor not in config.VENDORS:
        raise ValueError(f"unknown vendor {vendor!r}")
    heads: list[str] = []
    summaries: list[str] = []
    for name, role in roles().items():
        if not supports_vendor(role, vendor):
            continue
        try:
            entry = _entry(role, vendor)
            if role.get("required_model"):
                required_settings(role, vendor, account or "main")
        except ValueError:
            continue
        label = short_model(role["required_model"]) if role.get("required_model") else _hint_model(vendor, entry, account)
        heads.append(f"- bt-{name} ({label}, {entry['effort']}): ")
        summaries.append(_summary(role))
    return _compose(LEAD_HINT_PREFIX[vendor], heads, summaries, LEAD_HINT_LIMIT)


def check_report(models_cache=None) -> tuple[list[str], list[str]]:
    """(warnings, degraded): problems to fix, and roles that fall back down their chain on an account
    (plus accounts whose models cannot be verified because they have no models cache).

    Warnings: invalid entries, a Codex account that can use none of a chain, an effort the chosen
    model does not support, an unreadable models cache. A role served by a later chain entry is
    only reported as degraded. ``models_cache`` checks that one file as a single account.
    """
    warnings: list[str] = []
    degraded: list[str] = []
    targets = [("lead", _lead())] + [(f"bt-{name}", role) for name, role in roles().items()]
    for name in roles():
        if not ROLE_NAME.fullmatch(name):
            warnings.append(f"role {name!r}: name must be lowercase letters, digits and hyphens")
    codex: list[tuple[str, dict, dict]] = []
    for label, target in targets:
        for vendor in config.VENDORS:
            try:
                if not supports_vendor(target, vendor):
                    continue
                entry = _entry(target, vendor)
            except ValueError as exc:
                warnings.append(f"{label}: {exc}")
                continue
            if vendor == "claude":
                for model in entry_models(entry):
                    if not CLAUDE_MODEL.fullmatch(model):
                        warnings.append(f"{label}: claude model {model!r} does not match claude-(opus|sonnet|haiku|fable)-")
            else:
                codex.append((label, entry, target))
    if not codex:
        return warnings, degraded
    if models_cache:
        sources = [("codex", Path(models_cache))]
    else:
        sources = [(f"codex:{account}", config.account_dir("codex", account) / CACHE_NAME)
                   for account in config.account_names("codex")]
    for who, path in sources:
        catalog = _read_catalog(path)
        if catalog is None:
            line = f"{who}: codex models cache not found or unreadable at {path}; models not verified"
            (warnings if models_cache else degraded).append(line)  # an account that never ran codex is not an error
            continue
        account = who.partition(":")[2] or "main"
        for label, entry, target in codex:
            chain = entry_models(entry)
            effort = str(entry["effort"])
            if target.get("required_model"):
                required = target["required_model"]
                auth_stamp = config.mtime(path.parent / "auth.json")
                cache_stamp = config.mtime(path)
                if auth_stamp and (cache_stamp is None or auth_stamp > cache_stamp):
                    degraded.append(f"{label}: {who} catalog predates login; native CLI must validate exact {required}, no fallback")
                elif required not in catalog or effort not in catalog[required]:
                    warnings.append(f"{label}: {who} required model {required} with effort {effort} unavailable; no fallback")
                continue
            found = _resolve_in("codex", account, chain, effort, catalog)
            if found.model not in catalog:
                warnings.append(f"{label}: {who} can use none of {', '.join(chain)} (not in {path})")
                continue
            if found.degraded:
                degraded.append(f"{label}: {who} lacks {', '.join(chain[: chain.index(found.model)])}; falls back to {found.model}")
            if found.effort != effort:
                warnings.append(
                    f"{label}: effort {effort!r} is not supported by codex model {found.model!r} on {who} "
                    f"(supported: {', '.join(catalog[found.model]) or 'none'}); using {found.effort!r}"
                )
    return warnings, degraded


def check(models_cache=None) -> list[str]:
    """Warnings about the routing config; an empty list means nothing to report."""
    return check_report(models_cache)[0]


def _cmd_routing(args: argparse.Namespace) -> int:
    args.routing_parser.print_help()
    return 2


def _cmd_show(args: argparse.Namespace) -> int:
    vendors = [args.vendor] if args.vendor else list(config.VENDORS)
    for index, vendor in enumerate(vendors):
        if len(vendors) > 1:
            if index:
                print()
            print(f"[{vendor}]")
        print(lead_hint(vendor))
    return 0


def _cmd_apply(args: argparse.Namespace) -> int:
    actions = apply(dry_run=args.dry_run)
    if args.dry_run:
        print("dry run: no files written")
    for action in actions:
        print(action)
    if not actions:
        print("no roles configured")
    return 0


def _cmd_check(args: argparse.Namespace) -> int:
    warnings, degraded = check_report()
    for warning in warnings:
        print(f"warning: {warning}")
    for line in degraded:
        print(f"degraded: {line}")
    if not warnings:
        print("routing ok" + (" (degraded roles use their fallback models)" if degraded else ""))
    return 1 if warnings else 0


def register(subparsers) -> None:
    parser = subparsers.add_parser("routing", help="render role agents from routing.toml and show the lead's role table")
    parser.set_defaults(func=_cmd_routing, routing_parser=parser)
    sub = parser.add_subparsers(dest="routing_cmd", metavar="{show,apply,check}")

    show = sub.add_parser("show", help="print the lead's role table")
    show.add_argument("--vendor", choices=config.VENDORS, help="print one vendor's table (default: both)")
    show.set_defaults(func=_cmd_show)

    apply_parser = sub.add_parser("apply", help="write bt-<role> agent files to ~/.claude/agents and each Codex home's agents/")
    apply_parser.add_argument("--dry-run", action="store_true", help="report actions without writing")
    apply_parser.set_defaults(func=_cmd_apply)

    check_parser = sub.add_parser("check", help="per account, report roles whose models are unavailable (exit 1) or degraded")
    check_parser.set_defaults(func=_cmd_check)
