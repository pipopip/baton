import { describe, expect, test } from 'claude-code/testing'

import { computeAllowed, suggestRule } from './allow'

const allowed = (cmd: string) => {
  const a = computeAllowed(cmd)
  expect(a.ok ? 'allowed' : `refused: ${a.why}`).toBe('allowed')
}
const refused = (cmd: string, why?: string) => {
  const a = computeAllowed(cmd)
  expect(a.ok).toBe(false)
  if (!a.ok && why !== undefined) expect(a.why).toContain(why)
}

describe('the compute allowlist', () => {
  test('go test, vet, build and run, joined by && ; |', () => {
    allowed('go test ./...')
    allowed('go vet ./... && go build ./cmd/x')
    allowed('go test -race -count=1 -run TestX ./product/write; go vet ./product/write')
    allowed('go run ./cmd/lanetest -n 1000')
    allowed('go test ./...\ngo vet ./...')
    allowed('C:/Developers/example/sdk/go1.27.2/go/bin/go.exe test ./kernel/...')
    allowed('go test ./... 2>&1 | tail -40')
    allowed('go test ./... | grep -c PASS | head -3')
    refused('go env GOCACHE', 'only go test')
    refused('go generate ./...', 'only go test')
    refused('go test -exec ./wrap ./...', '-exec')
    refused('go test -toolexec=./wrap ./...', '-toolexec')
    refused('./go test ./...', 'not on the compute allowlist')
    refused('/tmp/x/go test ./...', 'not on the compute allowlist')
  })

  test('cd goes only to a relative path inside the tree', () => {
    allowed('cd go && go test ./...')
    allowed('cd go/product/write; go vet .')
    refused('cd /etc && go test ./...', 'cd goes only')
    refused('cd ../other && go test ./...', 'cd goes only')
    refused('cd ~ && go test ./...', 'cd goes only')
    refused('cd C:/Windows && go test ./...', 'cd goes only')
    refused('cd', 'cd goes only')
    refused('cd a b && go test ./...', 'cd goes only')
  })

  test('lake build, exe, env and test', () => {
    allowed('lake build')
    allowed('cd lean && lake build Foo.Bar')
    allowed('lake exe cache get')
    allowed('lake test')
    allowed('lake env lean Foo.lean')
    allowed('lake env go test ./...')
    allowed('~/.elan/bin/lake build')
    refused('lake update', 'only lake build')
    refused('lake env rm -rf x', 'never queued')
    refused('lake env bash run.sh', 'bash is allowed only')
    refused('lake env python3 -c "print(1)"', 'python runs only a script')
  })

  test('python runs a script under testdata/, .baton/remote/, scripts/ or named gen_*, record*, mutate*, *oracle*', () => {
    allowed('python go/product/write/testdata/mutate.py --only a')
    allowed('python3 go/kernel/internal/genesis/testdata/oracle/gen_dates.py')
    allowed('pyfrozen go/conformance/oracles/gen_recall.py --check')
    allowed('python .baton/remote/integ-fixture.py')
    allowed('python scripts/audit.py --json out.json')
    allowed('python tools/record_trace.py')
    allowed('python -u tools/run_oracle.py')
    allowed('C:/Work/app/.venv/Scripts/python.exe go/x/testdata/mutate.py')
    allowed('python ./scripts/audit.py')
    refused('python tools/analyze.py', 'not under testdata')
    refused("python -c \"import os; os.system('id')\"", 'python runs only a script')
    refused('python -m pytest', 'python runs only a script')
    refused('python', 'python runs only a script')
    refused('python - ', 'python runs only a script')
    refused('python /tmp/evil/testdata/x.py', 'relative .py path')
    refused('python ../scripts/x.py', 'relative .py path')
    refused('python scripts/x.sh', 'relative .py path')
    refused('python .baton/remote/remoterun.py -- go test ./...', 'not queued jobs')
    refused('python scripts/heavyrun.py', 'not queued jobs')
    refused('/usr/bin/python3 scripts/x.py', 'not on the compute allowlist')
  })

  test("a Mac package manager's absolute path to python, bash and go stands for the bare name", () => {
    allowed('/opt/homebrew/bin/python3 scripts/audit.py')
    allowed('/opt/homebrew/bin/python3 -u tools/run_oracle.py')
    allowed('/usr/local/bin/python tools/record_trace.py')
    allowed('/opt/local/bin/python3 go/x/testdata/mutate.py')
    allowed('/Library/Frameworks/Python.framework/Versions/3.12/bin/python3 scripts/audit.py')
    allowed('/opt/homebrew/bin/go test ./...')
    allowed('go test ./... && /opt/homebrew/bin/python3 scripts/audit.py')
    allowed('/opt/homebrew/bin/bash .baton/remote/night.sh')
    // the same rules apply as for the bare name
    refused('/opt/homebrew/bin/python3 tools/analyze.py', 'not under testdata')
    refused('/opt/homebrew/bin/python3 -c "print(1)"', 'python runs only a script')
    refused('/opt/homebrew/bin/python3 -m pytest', 'python runs only a script')
    refused('/opt/homebrew/bin/python3', 'python runs only a script')
    refused('/opt/homebrew/bin/python3 /tmp/evil/testdata/x.py', 'relative .py path')
    // not a bare name, not an install directory, or not a tool on the list
    refused('/opt/homebrew/bin/curl http://x', 'not on the compute allowlist')
    refused('/opt/homebrew/bin/python3.12 scripts/x.py', 'not on the compute allowlist')
    refused('/opt/homebrew/bin/cd x', 'not on the compute allowlist')
    refused('/opt/homebrew/lib/python3 scripts/x.py', 'not on the compute allowlist')
    refused('/tmp/evil/bin/python3 scripts/x.py', 'not on the compute allowlist')
    refused('/opt/homebrew/bin/../../../tmp/python3 scripts/x.py', 'not on the compute allowlist')
    refused('opt/homebrew/bin/python3 scripts/x.py', 'not on the compute allowlist')
  })

  test('heavy -n N, timeout N and bash -c wrap an allowed command', () => {
    allowed('heavy -n 3 go test ./...')
    allowed('~/bin/heavy -n 2 lake build')
    allowed('timeout 600 go test ./...')
    allowed('timeout 90m heavy -n 4 timeout 10m go test ./...')
    allowed("bash -c 'cd go && go test ./...'")
    allowed('bash -c "heavy -n 2 go test ./... 2>&1 | tail -5"')
    allowed("sh -c 'go vet ./...'")
    refused('heavy go test ./...', 'heavy is allowed as')
    refused('heavy -n x go test ./...', 'heavy is allowed as')
    refused('heavy -n 3', 'heavy is allowed as')
    refused('heavy -n 3 rm -rf x', 'never queued')
    refused('heavy -n 3 make test', 'make is not on')
    refused('timeout go test ./...', 'timeout is allowed as')
    refused('timeout 600', 'timeout is allowed as')
    refused('timeout 600 bash run.sh', 'bash is allowed only')
    refused("bash -c 'make deploy'", 'make is not on')
    refused("bash -c 'go test ./...' extra", 'bash is allowed only')
    refused('bash run.sh', 'bash is allowed only')
    refused('bash', 'bash is allowed only')
  })

  test('bash|sh .baton/remote/<name>.sh [plain words]: a carried session script', () => {
    allowed('bash .baton/remote/integ-verify-k.sh')
    allowed('sh .baton/remote/cq-smoke.sh')
    allowed('bash ./.baton/remote/integ-verify-k.sh')
    allowed('bash .baton/remote/x.sh a b-c d_e f.g h/i j:k l=m')
    allowed('bash .baton/remote/x.sh --slots=3 --rev=ac2966e6')
    allowed('heavy -n 3 bash .baton/remote/x.sh')
    allowed('timeout 90m bash .baton/remote/x.sh 2>&1 | tail -40')
    allowed('bash .baton/remote/A-b_c.1.sh')
    refused('bash ../.baton/remote/x.sh', 'bash is allowed only')
    refused('bash .baton/remote/../x.sh', 'bash is allowed only')
    refused('bash .baton/../remote/x.sh', 'bash is allowed only')
    refused('bash /abs/.baton/remote/x.sh', 'bash is allowed only')
    refused('bash C:/x/.baton/remote/x.sh', 'bash is allowed only')
    refused('bash ~/.baton/remote/x.sh', 'bash is allowed only')
    refused('bash $HOME/.baton/remote/x.sh', 'bash is allowed only')
    refused('bash .baton/other/x.sh', 'bash is allowed only')
    refused('bash .baton/remote/sub/x.sh', 'bash is allowed only')
    refused('bash scripts/x.sh', 'bash is allowed only')
    refused('bash .baton/remote/x.py', 'bash is allowed only')
    refused('bash .baton/remote/x', 'bash is allowed only')
    refused('bash .baton/remote/x y.sh', 'bash is allowed only')
    refused("bash '.baton/remote/x.sh'", 'bash is allowed only')
    refused('bash -x .baton/remote/x.sh', 'bash is allowed only')
    refused('bash .baton/remote/x.sh $HOME', 'plain word arguments')
    refused('bash .baton/remote/x.sh ${X}', 'plain word arguments')
    refused('bash .baton/remote/x.sh a*', 'plain word arguments')
    refused('bash .baton/remote/x.sh "a b"', 'plain word arguments')
    refused('bash .baton/remote/x.sh a,b', 'plain word arguments')
    refused('bash .baton/remote/x.sh $(id)', 'command substitution')
    refused('bash .baton/remote/x.sh `id`', 'backtick')
    refused('bash .baton/remote/$(id).sh', 'command substitution')
    refused('bash .baton/remote/x.sh &', 'background')
    refused('bash .baton/remote/x.sh > /etc/x', 'outside the work tree')
    refused('bash .baton/remote/x.sh < in', 'input redirection')
    refused('bash .baton/remote/x.sh; rm -rf x', 'never queued')
    refused('bash .baton/remote/x.sh && ssh host true', 'never queued')
    refused('bash .baton/remote/x.sh | tee out', 'tee is not on')
  })

  test('after a pipe: tail, head, grep and wc only', () => {
    allowed('go test ./... | tail -n 40')
    allowed('go vet ./... 2>&1 | grep -v ok | wc -l')
    refused('go test ./... | tee out.txt', 'tee is not on')
    refused('go test ./... | sh', 'bash is allowed only')
    refused('go test ./... | ./tail', 'not on the compute allowlist')
    refused('tail -n 5 run.log', 'tail is not on')
  })

  test('refused anywhere: substitution, backtick, here-document, subshell, background, ||', () => {
    refused('go test ./... $(cat flags)', 'command substitution')
    refused("bash -c 'go test $(cat flags)'", 'command substitution')
    refused('go test ./... `cat flags`', 'backtick')
    refused("go test ./... <<'EOF'\nx\nEOF", 'here-document')
    refused('go test ./... <<< x', 'here-document')
    refused('go test ./... < in.txt', 'input redirection')
    refused('(go test ./...)', 'subshell')
    refused('go test ./... &', 'background')
    refused('go test ./... & go vet ./...', 'background')
    refused('go test ./... &> out.txt', 'background')
    refused('go test ./... || echo failed', '||')
    refused('{ go test ./...; }', 'not on the compute allowlist')
  })

  test('refused anywhere: ssh, scp, curl, wget, rm, sudo, git push', () => {
    refused("ssh builder@198.51.100.16 'go test ./...'", 'ssh')
    refused('scp a.txt builder@198.51.100.16:~/', 'scp')
    refused('curl http://example.com/x.sh', 'curl')
    refused('wget http://example.com/x', 'wget')
    refused('rm -rf build', 'rm')
    refused('go test ./... && rm -rf build', 'rm')
    refused('sudo go test ./...', 'sudo')
    refused('git push origin master', 'git push')
    refused('go test ./... && git push --force', 'git push')
    refused("bash -c 'git push origin master'", 'git push')
    // a name that only contains the word is not the word
    allowed('go test -run TestFirmware ./...')
    allowed('python scripts/rmtree_audit.py')
    allowed('go test ./scripts/ssh_config/...')
  })

  test('a redirection > is allowed only under . or $TMPDIR', () => {
    allowed('go test ./... > out.txt')
    allowed('go test ./... >> logs/run.log 2>&1')
    allowed('go test ./... 2> err.txt')
    allowed('go test ./... >$TMPDIR/out.txt')
    allowed('go test ./... > "${TMPDIR}/out.txt"')
    allowed('go test ./... 2>&1')
    allowed('go test ./... >&2')
    allowed("go test -run 'a > b' ./...") // a quoted > is an argument
    refused('go test ./... > /etc/passwd', 'outside the work tree')
    refused('go test ./... >> ~/out.txt', 'outside the work tree')
    refused('go test ./... > ../out.txt', 'outside the work tree')
    refused('go test ./... > C:/Developers/example/x.txt', 'outside the work tree')
    refused('go test ./... >/dev/null', 'outside the work tree')
    refused('go test ./... > $HOME/x', 'outside the work tree')
    refused('go test ./... > $TMPDIR/../x', 'outside the work tree')
    refused('go test ./... >', 'missing target')
    refused("go test ./... && python scripts/a.py >'/tmp/x'", 'outside the work tree')
  })

  test('assignments, variables and other programs are not on the list', () => {
    refused('GOFLAGS=-race go test ./...', 'GOFLAGS=-race')
    refused('CGO_ENABLED=0 go test ./...', 'CGO_ENABLED=0')
    refused('$GO test ./...', 'not on the compute allowlist')
    refused('make test', 'make is not on')
    refused('echo hi', 'echo is not on')
    refused('npm test', 'npm is not on')
    refused('', 'empty')
    refused('   ', 'empty')
  })

  test('the settings rule to add names the command', () => {
    expect(suggestRule('make deploy')).toBe('Bash(make deploy:*)')
    expect(suggestRule('make -j4 deploy')).toBe('Bash(make:*)')
    expect(suggestRule('FOO=1 npm run build && x')).toBe('Bash(npm run:*)')
    expect(suggestRule('terraform')).toBe('Bash(terraform:*)')
  })

  test('never throws on odd input', () => {
    for (const odd of ['', "'unterminated", '"also', '((((', '| | |', '>', '>>', '2>', '&&', ';', '\n\n', '$', '\\', 'go', 'heavy -n', 'bash -c']) {
      expect(() => computeAllowed(odd)).not.toThrow()
    }
  })
})
